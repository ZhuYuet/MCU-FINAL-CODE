    MOV A, @R0
    LCALL LCD_DATA
    INC R0
    DJNZ R1, LOGIC_DRAW_LOOP
LOGIC_FILL_SPACES:
    MOV A, #LCD_WIDTH
    CLR C
    SUBB A, RX_BYTE
    MOV R1, A
    MOV A, R1
    JZ LOGIC_POSITION_CURSOR
LOGIC_SPACE_LOOP:
    MOV A, #' '
    LCALL LCD_DATA
    DJNZ R1, LOGIC_SPACE_LOOP
LOGIC_POSITION_CURSOR:
    MOV A, RX_BYTE
    CJNE A, #LCD_WIDTH, LOGIC_CURSOR_NOT_FULL
    DEC A                       
LOGIC_CURSOR_NOT_FULL:
    ADD A, #LCD_LINE1
    MOV INPUT_CURSOR_ADDR, A
    LJMP LCD_CMD

