    MOV A, DISPLAY_MODE
    CJNE A, #02H, LOGIC_SCROLL_DONE
    MOV A, EXPR_LEN
    CLR C
    SUBB A, #LCD_WIDTH
    JC LOGIC_SCROLL_DONE
