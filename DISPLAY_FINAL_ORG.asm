LOGIC_REDRAW:	;function
    MOV A, #LCD_LINE1
    LCALL LCD_CMD
    MOV R0, #EXPR_BUF
    MOV A, EXPR_VIEW
    ADD A, R0
    MOV R0, A
    MOV A, EXPR_LEN
    CLR C
    SUBB A, EXPR_VIEW
    MOV R1, A                   
    CJNE A, #LCD_WIDTH, LOGIC_VISIBLE_COMPARE
    SJMP LOGIC_VISIBLE_READY
