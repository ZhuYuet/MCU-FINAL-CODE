; ===== D07: UART Comunication =====
; The ISR captures one byte quickly. RECEIVE_BYTE consumes it and sends ACK.
UART_INIT:	;Function
    ANL TMOD, #0FH	;timer 1 reset to mode 0
    ORL TMOD, #020H	;set to mode 2: 8-bit timer 
    ANL PCON, #07FH	;0111 1111, Clear SMOD: normal UART baud rate
    MOV TH1, #0FDH	;253:Timer 1’s reload value, after overflow, reload to FDH
    MOV TL1, #0FDH	;load initial timer 1 value
    MOV SCON, #050H	;0101 0000， UART mode 1
    CLR TI
    CLR RI
    SETB TR1		;Sets the Timer 1 run-control bit in TCON
    RET

UART_ISR:	;function
    JNB RI, UART_ISR_CHECK_TI
    CLR RI
    MOV RX_ISR_BYTE, SBUF         ; Save byte without changing ACC or PSW
    SETB 21H.2                   ; RX_READY

UART_ISR_CHECK_TI:
    JNB TI, UART_ISR_DONE
    CLR TI

UART_ISR_DONE:
    RETI

RECEIVE_BYTE:	;function
RECEIVE_WAIT_BYTE:
    JNB 21H.2, RECEIVE_WAIT_BYTE ; RX_READY （repeat if 21H.2 is 0)

    ; Disable the serial interrupt while ACK is transmitted. Otherwise the
    ; shared serial ISR would clear TI before this routine observes it.
    CLR ES		;serial-interrupt enable bit.
    MOV A, RX_ISR_BYTE	;Return value
    CLR 21H.2 		; Clear RX_READY, reafy to receive another bytes
    PUSH ACC
    CLR TI		;clear transmit-complete flag
    MOV SBUF, #006H	; Send ACK
RECEIVE_WAIT_ACK_SENT:
    JNB TI, RECEIVE_WAIT_ACK_SENT	;proceed when transmit complete
    CLR TI	;clear TI flag
    SETB ES	;enable UART interrupt
    POP ACC
    RET
    
