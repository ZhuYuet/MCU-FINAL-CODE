LOGIC_BUFFER_RESET: 	;function
    MOV EXPR_LEN, #00H
    MOV EXPR_VIEW, #00H
    RET

LOGIC_APPEND_CHAR:	;function
    MOV RX_BYTE, A
    MOV A, EXPR_LEN
    CJNE A, #EXPR_MAX, LOGIC_APPEND_SPACE_AVAILABLE
    RET
LOGIC_APPEND_SPACE_AVAILABLE:
    MOV R0, #EXPR_BUF
    ADD A, R0
    MOV R0, A
    MOV A, RX_BYTE
    MOV @R0, A
    INC EXPR_LEN
    MOV A, EXPR_LEN
    CLR C
    SUBB A, #LCD_WIDTH
    JC LOGIC_APPEND_FIRST_WINDOW
    JZ LOGIC_APPEND_FIRST_WINDOW
    MOV EXPR_VIEW, A
    SJMP LOGIC_REDRAW
LOGIC_APPEND_FIRST_WINDOW:
    MOV EXPR_VIEW, #00H
    SJMP LOGIC_REDRAW

LOGIC_REPLACE_LAST_CHAR:	;function
    MOV RX_BYTE, A
    MOV A, EXPR_LEN
    JZ LOGIC_REPLACE_DONE
    DEC A
    ADD A, #EXPR_BUF
    MOV R0, A
    MOV A, RX_BYTE
    MOV @R0, A
    LCALL LOGIC_REDRAW
LOGIC_REPLACE_DONE:
    RET

